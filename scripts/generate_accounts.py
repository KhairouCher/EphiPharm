#!/usr/bin/env python3
"""Reset EPIPHARM accounts for the rebuild.

Reads the legacy USERS.PSW layout (already reverse-engineered: 8-byte username,
12-byte password field we could NOT reliably decode, 8-byte rights flags),
keeps the usernames and rights flags, and issues brand-new passwords hashed
with PBKDF2-HMAC-SHA256 (210,000 iterations, per-user salt).

Produces two files:
  - db/accounts_seed.sql       safe to commit: usernames, rights, password HASHES only
  - CREDENTIALS_DO_NOT_COMMIT.txt   plaintext temp passwords, for handing to staff directly.
    This file must never be committed or uploaded anywhere. Delete it once passwords
    are distributed and each account has logged in (the app should force a password
    change on first login).

Usage: python generate_accounts.py <path to USERS.PSW> <output_dir>
"""
import hashlib
import os
import secrets
import sys

ITERATIONS = 210_000
# Simple, typeable syllables (no accents, no ambiguous letters) + 2 digits from 2-9
# so low-literacy / low-typing-speed staff can read and enter them without confusion
# between 0/O or 1/l/I.
SYLL = ["ba", "bo", "da", "do", "fa", "fo", "ga", "go", "ja", "jo",
        "ka", "ko", "la", "lo", "ma", "mo", "na", "no", "ra", "ro",
        "sa", "so", "ta", "to", "va", "vo", "za", "zo"]
DIGITS = "23456789"


def make_password():
    word = "".join(secrets.choice(SYLL) for _ in range(3))
    digits = "".join(secrets.choice(DIGITS) for _ in range(2))
    return word + digits


def hash_password(password: str, salt: bytes) -> bytes:
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, ITERATIONS)


def read_users_psw(path):
    data = open(path, "rb").read()
    accounts = []
    for line in data.split(b"\r\n"):
        if not line or line == b"\x1a":
            continue
        username = line[0:8].decode("ascii", "replace").rstrip()
        rights = line[20:28].decode("ascii", "replace")
        accounts.append((username, rights))
    return accounts


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    psw_path, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)

    accounts = read_users_psw(psw_path)
    if not accounts:
        sys.exit("no accounts found in USERS.PSW")

    sql_path = os.path.join(out_dir, "accounts_seed.sql")
    handout_path = os.path.join(os.path.dirname(out_dir) or ".", "CREDENTIALS_DO_NOT_COMMIT.txt")

    sql_lines = [
        "-- Generated by scripts/generate_accounts.py -- DO NOT put plaintext passwords here.",
        "-- Usernames and rights flags are carried over from the legacy USERS.PSW.",
        "-- The legacy password field could not be reliably decoded (see session notes);",
        "-- every account gets a fresh PBKDF2-hashed password and must change it on first login.",
        "",
        "CREATE TABLE IF NOT EXISTS accounts (",
        "    id INTEGER PRIMARY KEY,",
        "    username TEXT NOT NULL UNIQUE,",
        "    legacy_rights TEXT NOT NULL,      -- raw 8-char flags from USERS.PSW, meaning not fully decoded yet",
        "    role TEXT NOT NULL,               -- 'admin' if legacy_rights[0]='O', else 'user' (best current guess)",
        "    password_hash BLOB NOT NULL,",
        "    password_salt BLOB NOT NULL,",
        "    pbkdf2_iterations INTEGER NOT NULL,",
        "    must_change_password INTEGER NOT NULL DEFAULT 1,",
        "    created_at TEXT NOT NULL DEFAULT (datetime('now'))",
        ");",
        "",
    ]

    handout_lines = [
        "EPIPHARM rebuild - temporary login credentials",
        "================================================",
        "Give each line below to that person directly (in person or a private message),",
        "never to a group chat. Everyone must change their password on first login.",
        "Delete this file once every account has logged in once.",
        "",
    ]

    for username, rights in accounts:
        role = "admin" if rights[:1] == "O" else "user"
        password = make_password()
        salt = secrets.token_bytes(16)
        pwhash = hash_password(password, salt)
        esc_user = username.replace("'", "''")
        sql_lines.append(
            "INSERT INTO accounts (username, legacy_rights, role, password_hash, "
            "password_salt, pbkdf2_iterations) VALUES ("
            f"'{esc_user}', '{rights}', '{role}', "
            f"X'{pwhash.hex()}', X'{salt.hex()}', {ITERATIONS});"
        )
        handout_lines.append(f"{username:10s} role={role:5s} password: {password}")

    open(sql_path, "w").write("\n".join(sql_lines) + "\n")
    open(handout_path, "w").write("\n".join(handout_lines) + "\n")

    print(f"{len(accounts)} accounts processed")
    print(f"  seed SQL (safe to commit):      {sql_path}")
    print(f"  plaintext handout (DO NOT commit): {handout_path}")


if __name__ == "__main__":
    main()
